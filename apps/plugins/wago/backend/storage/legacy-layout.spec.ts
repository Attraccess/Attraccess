import { randomBytes } from 'node:crypto';
import { Client } from 'pg';
import type { PluginStorageField, PluginStorageTable } from '@attraccess/plugins-backend-sdk';
import { WAGO_LEGACY_MIGRATION_SQL } from './legacy-layout.fixture';
import { WAGO_LEGACY_MIGRATIONS, wagoStorage, wagoTables } from './index';

jest.setTimeout(60_000);

interface ColumnInfo {
  name: string;
  type: string;
  notnull: boolean;
  dflt_value: string | null;
  pk: number;
}
interface IndexInfo {
  unique: boolean;
  columns: string[];
}
interface ForeignKeyInfo {
  from: string;
  table: string;
  to: string;
  onDelete: string;
}

// The same server as the host's specs (testAdminUrl in apps/api/src/test-utils/test-database.ts, which a plugin may
// not import): TEST_DATABASE_URL, then DATABASE_URL, then the shared dev PostgreSQL on its default port.
const ADMIN_URL =
  process.env.TEST_DATABASE_URL ||
  process.env.DATABASE_URL ||
  'postgres://attraccess:attraccess@127.0.0.1:5432/postgres';

/**
 * The 1.x migrations were written for SQLite; the fixture keeps their statements verbatim. The only construct
 * PostgreSQL does not know is the SQLite auto-increment key, which is translated to the identity column the
 * host's engine creates. The layout is replayed into a throwaway PostgreSQL database and read back from the catalog.
 */
const toPostgres = (statement: string) =>
  statement.replace('PRIMARY KEY AUTOINCREMENT NOT NULL', 'GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');

/** The schema an installed 1.x database has: every legacy migration replayed in order, on an isolated database. */
async function legacyDatabase(): Promise<{ client: Client; drop(): Promise<void> }> {
  const name = `att_wago_legacy_${randomBytes(6).toString('hex')}`;
  const admin = new Client({ connectionString: ADMIN_URL });
  await admin.connect();
  await admin.query(`CREATE DATABASE "${name}"`);
  const url = new URL(ADMIN_URL);
  url.pathname = `/${name}`;
  const client = new Client({ connectionString: url.toString() });
  await client.connect();
  try {
    for (const [, statements] of WAGO_LEGACY_MIGRATION_SQL)
      for (const statement of statements) await client.query(toPostgres(statement));
  } catch (error) {
    await client.end();
    await admin.query(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`);
    await admin.end();
    throw error;
  }
  return {
    client,
    drop: async () => {
      await client.end();
      await admin.query(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`);
      await admin.end();
    },
  };
}

const columnOf = (name: string, field: PluginStorageField) => field.column ?? name;
const physicalName = (definition: PluginStorageTable) => definition.physicalName as string;

/** Storage class of a catalog type name; varchar, text, integer and bigint are the 1.x column types. */
function affinity(declared: string): 'text' | 'integer' {
  if (declared === 'integer' || declared === 'bigint') return 'integer';
  if (declared === 'character varying' || declared === 'text') return 'text';
  throw new Error(`Unexpected legacy column type ${declared}`);
}

function declaredAffinity(field: PluginStorageField): 'text' | 'integer' {
  if (field.type === 'integer') return 'integer';
  if (field.type === 'string' || field.type === 'text') return 'text';
  throw new Error(`The 1.x layout has no ${field.type} column`);
}

function defaultLiteral(raw: string | null): string | number | null {
  if (raw === null) return null;
  const unwrapped = raw.replace(/::[a-z ]+$/, '');
  if (/^'[\s\S]*'$/.test(unwrapped)) return unwrapped.slice(1, -1);
  return Number(unwrapped);
}

const bySorted = <T>(values: T[]) => [...values].sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b)));

const DELETE_ACTION: Record<string, string> = {
  a: 'restrict',
  r: 'restrict',
  c: 'cascade',
  n: 'set null',
  d: 'set default',
};

describe('WAGO storage baseline against the 1.x migrations', () => {
  let legacy: { client: Client; drop(): Promise<void> };
  beforeAll(async () => {
    legacy = await legacyDatabase();
  });
  afterAll(async () => {
    await legacy?.drop();
  });

  const tables = Object.entries(wagoTables) as [string, PluginStorageTable][];

  const columnsOfTable = async (table: string): Promise<ColumnInfo[]> =>
    (
      await legacy.client.query(
        `SELECT a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type,
                a.attnotnull AS notnull,
                CASE WHEN a.attidentity <> '' THEN NULL ELSE pg_get_expr(d.adbin, d.adrelid) END AS dflt_value,
                COALESCE(array_position(i.indkey::int2[], a.attnum) + 1, 0) AS pk
           FROM pg_attribute a
           LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
           LEFT JOIN pg_index i ON i.indrelid = a.attrelid AND i.indisprimary
          WHERE a.attrelid = $1::regclass AND a.attnum > 0 AND NOT a.attisdropped`,
        [`"${table}"`],
      )
    ).rows;

  it('declares exactly the tables the legacy migrations leave behind', async () => {
    const existing = (
      await legacy.client.query(
        `SELECT table_name AS name FROM information_schema.tables WHERE table_schema = 'public' AND table_type = 'BASE TABLE'`,
      )
    ).rows.map(({ name }: { name: string }) => name);
    expect(bySorted(tables.map(([, definition]) => physicalName(definition)))).toEqual(bySorted(existing));
  });

  it.each(tables)('matches the columns, defaults and keys of %s', async (_name, definition) => {
    const table = physicalName(definition);
    const columns = await columnsOfTable(table);
    const declared = Object.entries(definition.fields).map(([name, field]) => ({
      column: columnOf(name, field),
      notnull: !field.nullable,
      affinity: declaredAffinity(field),
      default: field.hasDefault && !field.generated ? field.default : null,
    }));
    const existing = columns.map((column) => ({
      column: column.name,
      notnull: column.notnull || column.pk > 0,
      affinity: affinity(column.type),
      default: defaultLiteral(column.dflt_value),
    }));
    expect(bySorted(declared)).toEqual(bySorted(existing));

    const primaryKey = columns
      .filter((column) => column.pk > 0)
      .sort((a, b) => a.pk - b.pk)
      .map((column) => column.name);
    expect(definition.primaryKey.map((name) => columnOf(name, definition.fields[name]))).toEqual(primaryKey);

    const identity = (
      await legacy.client.query(
        `SELECT count(*)::int AS n FROM pg_attribute WHERE attrelid = $1::regclass AND attidentity <> '' AND NOT attisdropped`,
        [`"${table}"`],
      )
    ).rows[0].n;
    const generated = Object.values(definition.fields).some((field) => field.generated);
    expect(identity > 0).toBe(generated);
  });

  it.each(tables)('matches the unique keys and indexes of %s', async (_name, definition) => {
    const table = physicalName(definition);
    const existing: IndexInfo[] = (
      await legacy.client.query(
        `SELECT i.indisunique AS "unique",
                ARRAY(SELECT a.attname::text FROM unnest(i.indkey::int2[]) WITH ORDINALITY k(attnum, ord)
                        JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.attnum ORDER BY k.ord) AS columns
           FROM pg_index i WHERE i.indrelid = $1::regclass AND NOT i.indisprimary`,
        [`"${table}"`],
      )
    ).rows;
    const declared = definition.indexes.map((index) => ({
      unique: index.unique === true,
      columns: index.fields.map((name) => columnOf(name, definition.fields[name])),
    }));
    expect(bySorted(declared)).toEqual(bySorted(existing));
  });

  it.each(tables)('matches the foreign keys of %s', async (_name, definition) => {
    const table = physicalName(definition);
    const existing: ForeignKeyInfo[] = (
      await legacy.client.query(
        `SELECT a.attname AS "from", c.confrelid::regclass::text AS "table", ra.attname AS "to", c.confdeltype AS action
           FROM pg_constraint c
           JOIN LATERAL unnest(c.conkey, c.confkey) AS k(attnum, refnum) ON true
           JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.attnum
           JOIN pg_attribute ra ON ra.attrelid = c.confrelid AND ra.attnum = k.refnum
          WHERE c.conrelid = $1::regclass AND c.contype = 'f'`,
        [`"${table}"`],
      )
    ).rows.map((row: { from: string; table: string; to: string; action: string }) => ({
      from: row.from,
      table: row.table.replace(/^"|"$/g, ''),
      to: row.to,
      onDelete: DELETE_ACTION[row.action],
    }));
    const declared = definition.foreignKeys.flatMap((key) =>
      key.fields.map((name, index) => {
        const target = wagoTables[key.references as keyof typeof wagoTables];
        const targetField = key.referencedFields[index];
        return {
          from: columnOf(name, definition.fields[name]),
          table: physicalName(target),
          to: columnOf(targetField, target.fields[targetField]),
          onDelete: key.onDelete === 'cascade' ? 'cascade' : key.onDelete === 'set-null' ? 'set null' : 'restrict',
        };
      }),
    );
    expect(bySorted(declared)).toEqual(bySorted(existing));
  });

  it('keeps every physical name inside the plugin namespace', () => {
    for (const [, definition] of tables) expect(physicalName(definition)).toMatch(/^plugin_wago_[a-z_]+$/);
  });
});

describe('WAGO storage definition', () => {
  it('adopts a database where all nineteen legacy migrations are applied, in execution order', () => {
    expect(wagoStorage.adoption?.legacyMigrations).toEqual(WAGO_LEGACY_MIGRATIONS);
    expect(WAGO_LEGACY_MIGRATIONS).toHaveLength(19);
    expect(WAGO_LEGACY_MIGRATION_SQL.map(([name]) => name)).toEqual([...WAGO_LEGACY_MIGRATIONS]);
    const timestamps = WAGO_LEGACY_MIGRATIONS.map((name) => Number(/\d+$/.exec(name)?.[0]));
    expect(timestamps).toEqual([...timestamps].sort((a, b) => a - b));
    expect(new Set(WAGO_LEGACY_MIGRATIONS).size).toBe(19);
  });

  it('ships the declared layout as baseline version 1 and creates referenced tables first', () => {
    expect(wagoStorage.migrations.map((migration) => migration.version)).toEqual([1]);
    const created = (wagoStorage.migrations[0].steps ?? []).map((item) =>
      item.op === 'createTable' ? item.table : '',
    );
    expect(created).toEqual(Object.keys(wagoTables));
    for (const item of wagoStorage.migrations[0].steps ?? []) {
      if (item.op !== 'createTable') continue;
      expect(item.definition).toBe(wagoTables[item.table as keyof typeof wagoTables]);
      for (const key of item.definition.foreignKeys)
        expect(created.indexOf(key.references)).toBeLessThan(created.indexOf(item.table));
    }
  });
});
