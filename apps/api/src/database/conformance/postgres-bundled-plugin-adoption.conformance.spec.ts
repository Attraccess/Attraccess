import {
  type CompiledPluginStorage,
  PluginStorageMigrationFailed,
  PluginStorageMigrationRefused,
  legacyMigrationsTableName,
  versionsTableName,
} from '../../plugin-system/plugin-storage/storage-model';
import { compilePluginStorage } from '../../plugin-system/plugin-storage/storage-schema';
import {
  type BundledPluginStorage,
  BUNDLED_PLUGINS,
  loadBundledPlugins,
} from './plugin-storage/bundled-plugins.test-fixture';
import { tablesInOrder, writeRow } from './plugin-storage/legacy-adoption.test-fixture';
import { postgresStorageFixture, removePostgresTemplate } from './plugin-storage/postgres-plugin-storage.test-fixture';
import type { StorageDatabase } from './plugin-storage/storage-fixture';

jest.setTimeout(120_000);

type Row = Record<string, unknown>;
type Tables = Record<
  string,
  { find(query?: object): Promise<Row[]>; insert(row: object): Promise<Row>; delete(where: object): Promise<number> }
>;

/**
 * Adoption of existing plugin tables by the host engine, on real PostgreSQL: each bundled plugin's own storage
 * declaration. 1.x ran on SQLite only and the SQLite import moves no plugin data, so the adopted layout here is what
 * this engine's DDL creates for the declaration's baseline, stripped of the host's version bookkeeping and given the
 * legacy migrations table a 1.x installation carried. The baseline is version 1; later versions run after adoption.
 */
describe.each(BUNDLED_PLUGINS)('adoption of existing tables by the bundled plugin %s (postgres)', (pluginName) => {
  let plugin: BundledPluginStorage;
  let compiled: CompiledPluginStorage;
  /** The release that knows only the baseline: what adoption itself records. */
  let baseline: CompiledPluginStorage;
  const databases: StorageDatabase[] = [];

  const database = async () => {
    const db = await postgresStorageFixture.create();
    databases.push(db);
    return db;
  };
  const tablesOf = async (db: StorageDatabase, storage: CompiledPluginStorage): Promise<Tables> => {
    const side = await db.connect();
    return side.contexts(pluginName, storage).storage.open(plugin.storage as never) as never as Tables;
  };

  /** Writes one row into every table through the record port, parents first; returns the rows as read back. */
  async function seedRows(db: StorageDatabase): Promise<Map<string, Row>> {
    const tables = await tablesOf(db, baseline);
    const written = new Map<string, Row>();
    for (const table of tablesInOrder(baseline, baseline.tables)) {
      written.set(table.logical, await tables[table.logical].insert(writeRow(table, written)));
    }
    return written;
  }

  /**
   * The part of a seeded row that the later versions keep. A version may replace a column (drop it and add it with a
   * new definition, as WAGO does for its overflowing integer columns); that field starts over, every other one must
   * read back unchanged.
   */
  function kept(logical: string, row: Row): Row {
    const before = baseline.tables.get(logical)?.fields;
    const after = compiled.tables.get(logical)?.fields;
    return Object.fromEntries(
      Object.entries(row).filter(([field]) => JSON.stringify(before?.get(field)) === JSON.stringify(after?.get(field))),
    );
  }

  /** Leaves the tables as a pre-existing installation has them: no version bookkeeping, the legacy history instead. */
  async function becomeLegacy(db: StorageDatabase, applied: readonly string[]): Promise<void> {
    const legacy = `"${legacyMigrationsTableName(plugin.name)}"`;
    await db.execute(`DROP TABLE "${versionsTableName(compiled.namespace)}"`);
    await db.execute(
      `CREATE TABLE ${legacy} ("id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "timestamp" bigint NOT NULL, "name" varchar NOT NULL)`,
    );
    for (const [index, name] of applied.entries()) {
      await db.execute(`INSERT INTO ${legacy} ("timestamp", "name") VALUES (${1700000000000 + index}, '${name}')`);
    }
  }

  beforeAll(async () => {
    plugin = (await loadBundledPlugins()).find((candidate) => candidate.name === pluginName) as BundledPluginStorage;
    const db = await database();
    compiled = compilePluginStorage(pluginName, plugin.storage, { reservedTables: db.coreTables() });
    baseline = { ...compiled, migrations: compiled.migrations.slice(0, 1), tables: compiled.migrations[0].schemaAfter };
  });

  afterEach(async () => {
    await Promise.all(databases.splice(0).map((db) => db.close()));
  });

  afterAll(removePostgresTemplate);

  it('creates the whole history on a fresh install, and the rows of every table write and read', async () => {
    const db = await database();
    expect(await db.engine.migrate(compiled)).toEqual({
      pending: compiled.migrations.map((migration) => migration.version),
      adopt: false,
    });
    expect(await db.tables()).toEqual(
      expect.arrayContaining([...compiled.tables.values()].map((table) => table.physical)),
    );

    const tables = await tablesOf(db, compiled);
    const written = new Map<string, Row>();
    for (const table of tablesInOrder(compiled, compiled.tables)) {
      const row = await tables[table.logical].insert(writeRow(table, written));
      written.set(table.logical, row);
      expect(await tables[table.logical].find()).toEqual([row]);
    }
    expect(written.size).toBeGreaterThan(0);
  });

  it('adopts a complete existing history as version 1 without running DDL, and the rows read and write', async () => {
    const versions = versionsTableName(compiled.namespace);
    const db = await database();
    await db.engine.migrate(baseline);
    const expected = await seedRows(db);
    await becomeLegacy(db, plugin.storage.adoption?.legacyMigrations ?? []);
    const before = await db.snapshot();

    expect(await db.engine.migrate(baseline)).toEqual({ pending: [], adopt: true });

    expect(await db.snapshot({ except: [versions] })).toBe(before);
    expect(await db.committed(`SELECT "version", "source" FROM "${versions}"`)).toEqual([
      { version: 1, source: 'adopted' },
    ]);

    // Later versions of the history (if any) run on top of the adopted tables.
    const later = compiled.migrations.slice(1).map((migration) => migration.version);
    expect(await db.engine.migrate(compiled)).toEqual({ pending: later, adopt: false });

    const tables = await tablesOf(db, compiled);
    for (const [logical, row] of expected)
      expect([logical, await tables[logical].find()]).toEqual([logical, [expect.objectContaining(kept(logical, row))]]);
    // Writes of this release land in the adopted columns: clear the rows (children first), then write them again.
    const ordered = tablesInOrder(compiled, compiled.tables);
    for (const table of [...ordered].reverse()) {
      expect(await tables[table.logical].delete({})).toBe(1);
    }
    const written = new Map<string, Row>();
    for (const table of ordered) {
      written.set(table.logical, await tables[table.logical].insert(writeRow(table, written)));
      expect(await tables[table.logical].find()).toEqual([written.get(table.logical)]);
    }
  });

  it('adopts the 1.x history and tables under the npm package name the marketplace installs (ATT-1402)', async () => {
    const npmName = `@attraccess/plugin-${pluginName}`;
    const db = await database();
    const asNpm = compilePluginStorage(npmName, plugin.storage, { reservedTables: db.coreTables() });
    await db.engine.migrate(baseline);
    const expected = await seedRows(db);
    await becomeLegacy(db, plugin.storage.adoption?.legacyMigrations ?? []);

    const later = asNpm.migrations.slice(1).map((migration) => migration.version);
    expect(await db.engine.migrate(asNpm)).toEqual({ pending: later, adopt: true });

    const side = await db.connect();
    const tables = side.contexts(npmName, asNpm).storage.open(plugin.storage as never) as never as Tables;
    for (const [logical, row] of expected)
      expect([logical, await tables[logical].find()]).toEqual([logical, [expect.objectContaining(kept(logical, row))]]);
  });

  it('refuses a partial existing history and changes nothing', async () => {
    const legacy = compiled.legacyMigrations;
    const db = await database();
    await db.engine.migrate(baseline);
    await seedRows(db);
    await becomeLegacy(db, legacy.slice(0, -1));
    const before = await db.snapshot();

    // With a single 1.x migration, an empty history is a fresh install: creating the existing tables fails and rolls back.
    const expectedError = legacy.length > 1 ? PluginStorageMigrationRefused : PluginStorageMigrationFailed;
    await expect(db.engine.migrate(compiled)).rejects.toBeInstanceOf(expectedError);
    if (legacy.length > 1) {
      await expect(db.engine.migrate(compiled)).rejects.toThrow(/update to Attraccess 1\.11 and start it once/);
    }

    expect(await db.snapshot()).toBe(before);
  });
});
