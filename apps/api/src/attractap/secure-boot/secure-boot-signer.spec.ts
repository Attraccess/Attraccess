import { createPrivateKey, generateKeyPairSync } from 'crypto';
import { readFileSync } from 'fs';
import { join } from 'path';
import { crc32 } from 'zlib';
import {
  LAB_SECURE_BOOT_KEY_DIGESTS,
  publicKeyFingerprint,
  SECURE_BOOT_SECTOR_SIZE,
  SECURE_BOOT_SIG_BLOCK_SIZE,
  secureBootKeyDigest,
  signSecureBootImage,
  verifySecureBootImage,
} from './secure-boot-signer';

const fixture = (name: string) => readFileSync(join(__dirname, 'fixtures', name));

describe('secure boot v2 signer', () => {
  const image = fixture('image.bin');
  const keyPem = fixture('throwaway-key.pem').toString();
  const espsecureSigned = fixture('image.signed.bin');

  // Signature bytes (PSS is randomised) and the CRC that covers them differ per run;
  // everything before the signature must be byte-identical to espsecure's output.
  const sigStart = 4 + 32 + 384 + 4 + 384 + 4;

  it('produces the same signed layout as espsecure', () => {
    const ours = signSecureBootImage(image, keyPem);
    expect(ours.length).toBe(espsecureSigned.length);
    const contentsLength = ours.length - SECURE_BOOT_SECTOR_SIZE;
    expect(ours.subarray(0, contentsLength).equals(espsecureSigned.subarray(0, contentsLength))).toBe(true);
    const ourBlock = ours.subarray(contentsLength);
    const refBlock = espsecureSigned.subarray(contentsLength);
    expect(ourBlock.subarray(0, sigStart).equals(refBlock.subarray(0, sigStart))).toBe(true);
    expect(ourBlock.subarray(SECURE_BOOT_SIG_BLOCK_SIZE).equals(refBlock.subarray(SECURE_BOOT_SIG_BLOCK_SIZE))).toBe(
      true,
    );
    // CRC32 over the first 1196 bytes, then 16 padding bytes, exactly as espsecure lays them out.
    expect(ourBlock.readUInt32LE(1196)).toBe(crc32(ourBlock.subarray(0, 1196)));
    expect(refBlock.readUInt32LE(1196)).toBe(crc32(refBlock.subarray(0, 1196)));
    expect(
      ourBlock.subarray(1200, SECURE_BOOT_SIG_BLOCK_SIZE).equals(refBlock.subarray(1200, SECURE_BOOT_SIG_BLOCK_SIZE)),
    ).toBe(true);
  });

  it('refuses to sign an image that already carries a signature sector', () => {
    expect(() => signSecureBootImage(espsecureSigned, keyPem)).toThrow(/already carries/);
  });

  it('signs a sector-aligned image without extra padding', () => {
    const aligned = Buffer.alloc(2 * SECURE_BOOT_SECTOR_SIZE, 0x5a);
    const ours = signSecureBootImage(aligned, keyPem);
    expect(ours.length).toBe(3 * SECURE_BOOT_SECTOR_SIZE);
    expect(ours.subarray(0, aligned.length).equals(aligned)).toBe(true);
    expect(verifySecureBootImage(ours, keyPem).valid).toBe(true);
  });

  it('verifies a signature block generated by espsecure', () => {
    expect(verifySecureBootImage(espsecureSigned, keyPem).valid).toBe(true);
  });

  it('verifies its own output and rejects tampering', () => {
    const ours = signSecureBootImage(image, keyPem);
    expect(verifySecureBootImage(ours, keyPem).valid).toBe(true);
    const tampered = Buffer.from(ours);
    tampered[10] ^= 0x01;
    expect(verifySecureBootImage(tampered, keyPem).valid).toBe(false);
  });

  it('rejects a signature made by a different key', () => {
    const other = generateKeyPairSync('rsa', { modulusLength: 3072 }).privateKey;
    const ours = signSecureBootImage(image, other);
    expect(verifySecureBootImage(ours, keyPem).valid).toBe(false);
  });

  it('rejects keys that are not RSA-3072', () => {
    const small = generateKeyPairSync('rsa', { modulusLength: 2048 }).privateKey;
    expect(() => signSecureBootImage(image, small)).toThrow(/RSA-3072/);
    expect(verifySecureBootImage(espsecureSigned, small).valid).toBe(false);
  });

  it('computes the same eFuse key digest as espsecure digest-sbv2-public-key', () => {
    expect(secureBootKeyDigest(createPrivateKey(keyPem))).toBe(
      '247299cee1b5d78f6bd72ad92cc4e2b148ec077b68bf8725f71381f4df144ddc',
    );
  });

  it('reports a stable key digest and fingerprint', () => {
    const ours = signSecureBootImage(image, keyPem);
    expect(verifySecureBootImage(ours, keyPem).keyDigest).toBe(secureBootKeyDigest(createPrivateKey(keyPem)));
    expect(publicKeyFingerprint(createPrivateKey(keyPem))).toMatch(/^[0-9a-f]{64}$/);
  });

  describe('lab key guard', () => {
    const labDir = join(__dirname, '../../../../attractap/firmware/lab/secure-boot');

    it.each(['lab-signing-key.pem', 'lab-recovery-key.pem'])('refuses to sign with %s', (file) => {
      const pem = readFileSync(join(labDir, file)).toString();
      expect(LAB_SECURE_BOOT_KEY_DIGESTS.has(secureBootKeyDigest(createPrivateKey(pem)))).toBe(true);
      expect(() => signSecureBootImage(image, pem)).toThrow(/device-lab/);
    });

    it('does not block other keys', () => {
      expect(LAB_SECURE_BOOT_KEY_DIGESTS.has(secureBootKeyDigest(createPrivateKey(keyPem)))).toBe(false);
    });
  });
});
