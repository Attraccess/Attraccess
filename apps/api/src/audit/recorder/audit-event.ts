import type { PluginAuditReceipt } from '@attraccess/plugins-backend-sdk';
import type { EntityManager } from 'typeorm';
import type { AttractapAuditAction } from '../policies/attractap';
import type { AdministrationAuditAction, PreviousAuditSettings } from '../policies/administration';
import type {
  BILLING_AUDIT_ACTIONS,
  CORE_SUBJECT_TYPES,
  CoreAuditDomain,
  PROJECT_AUDIT_ACTIONS,
  SSO_AUDIT_ACTIONS,
} from '../policies/domains';
import type { IdentityAuditAction } from '../policies/identity';
import type { RESOURCE_AUDIT_ACTIONS } from '../policies/resources';

/**
 * The persisted action strings of every core audit domain. The envelope carries the stored action exactly as it
 * appears in the audit log, prefixes included.
 */
export interface CoreAuditActionMap {
  administration: AdministrationAuditAction;
  attractap: `attractap.${AttractapAuditAction}`;
  billing: (typeof BILLING_AUDIT_ACTIONS)[number];
  identity: `identity.${IdentityAuditAction}`;
  project: (typeof PROJECT_AUDIT_ACTIONS)[number];
  resource: (typeof RESOURCE_AUDIT_ACTIONS)[number];
  sso: (typeof SSO_AUDIT_ACTIONS)[number];
}

/** A domain a plugin registered through the plugin audit registry. Only the plugin audit host creates these. */
export type PluginAuditDomainName = string & { readonly __pluginAuditDomain: true };

export type AuditDomain = CoreAuditDomain | PluginAuditDomainName;

export type CoreAuditSubjectType = (typeof CORE_SUBJECT_TYPES)[number];

/**
 * Who made the change. `authenticationMethod` is null when no session or API token exists, for example a flow,
 * an MQTT message or a reader acting on its own; `id` is then the reader-linked user or null.
 */
export interface AuditActor {
  id: number | null;
  authenticationMethod: 'session' | 'api-token' | null;
  apiTokenId?: number | null;
}

/** The actor of a change that no user started (flows, schedulers, readers acting on their own). */
export const SYSTEM_AUDIT_ACTOR: AuditActor = Object.freeze({ id: null, authenticationMethod: null });

/** The actor of an authenticated HTTP or plugin request (session or API token). */
export function auditActorOf(user: {
  id: number;
  authenticationMethod?: 'session' | 'api-token';
  apiTokenId?: number | null;
}): AuditActor {
  const viaToken = user.authenticationMethod === 'api-token';
  return {
    id: user.id,
    authenticationMethod: viaToken ? 'api-token' : 'session',
    ...(viaToken && user.apiTokenId != null ? { apiTokenId: user.apiTokenId } : {}),
  };
}

/** Who made a change and, for identity events, the request it came with. */
export interface AuditOrigin {
  actor: AuditActor;
  request?: { ipAddress?: string; userAgent?: string };
}

/** The origin of an authenticated HTTP request: its user, client address and user agent. */
export function auditOriginOf(request: {
  user: Parameters<typeof auditActorOf>[0];
  ip?: string;
  headers?: Record<string, string | string[] | undefined>;
}): AuditOrigin {
  const userAgent = request.headers?.['user-agent'];
  return {
    actor: auditActorOf(request.user),
    request: { ipAddress: request.ip, userAgent: typeof userAgent === 'string' ? userAgent : undefined },
  };
}

export type AuditDetails = Record<string, string | number | boolean | null>;

interface AuditEnvelope<D extends AuditDomain, A, S> {
  domain: D;
  action: A;
  /** Generated by the recorder when omitted. */
  operationId?: string;
  actor: AuditActor;
  /** `id` is null only for identity events without a known user, e.g. a failed login for an unknown name. */
  subject: { type: S; id: number | null };
  /** Defaults to `succeeded`. */
  outcome?: 'attempted' | 'succeeded' | 'failed';
  /** Recorded for the identity domain only. */
  request?: { ipAddress?: string; userAgent?: string };
  details: AuditDetails;
}

/** The one audit event shape. The recorder derives the stored `pluginId` from `domain`. */
export type AuditEvent<D extends AuditDomain = AuditDomain> = D extends CoreAuditDomain
  ? AuditEnvelope<D, CoreAuditActionMap[D], CoreAuditSubjectType>
  : AuditEnvelope<PluginAuditDomainName, string, string>;

export interface AuditRecordOptions {
  /**
   * The audit settings before an administration `settings.updated` change of an `audit.*` key. When they
   * recorded administration events, the change that turns recording off is itself recorded.
   */
  previousAuditSettings?: PreviousAuditSettings;
}

/**
 * Records one audit event. Never rejects, except with AuditTransactionAbortedError when SQLite discarded the
 * caller's whole transaction. With `manager` inside an active transaction the row commits or rolls back with it.
 */
export interface AuditRecorder {
  record(event: AuditEvent, manager?: EntityManager, options?: AuditRecordOptions): Promise<PluginAuditReceipt>;
}

export const AUDIT_RECORDER = Symbol('AUDIT_RECORDER');
